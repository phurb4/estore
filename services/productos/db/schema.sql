-- Products service schema (PostgreSQL).
-- Idempotent: safe to run more than once. Run it inside one transaction
-- (psql --single-transaction), so this file has no BEGIN/COMMIT.
-- No credentials, users or addresses belong in this file.

CREATE TABLE IF NOT EXISTS categories (
    id   SMALLINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    slug TEXT NOT NULL UNIQUE CHECK (slug ~ '^[a-z0-9-]+$'),
    name TEXT NOT NULL UNIQUE CHECK (length(name) BETWEEN 1 AND 60)
);

CREATE TABLE IF NOT EXISTS products (
    id                   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                 TEXT NOT NULL CHECK (length(name) BETWEEN 1 AND 120),
    description          TEXT NOT NULL CHECK (length(description) BETWEEN 1 AND 200),
    category_id          SMALLINT NOT NULL REFERENCES categories (id) ON DELETE RESTRICT,
    price                NUMERIC(10,2) NOT NULL CHECK (price >= 0 AND price <= 10000000),
    -- File name only. The API prepends "img/" (see frontend/js/store.js).
    image_file           TEXT NOT NULL CHECK (image_file ~ '^[A-Za-z0-9_-]+\.(png|jpe?g|webp|gif)$'),
    image_is_placeholder BOOLEAN NOT NULL DEFAULT FALSE,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS products_category_id_idx ON products (category_id);
